BEGIN;

CREATE TABLE IF NOT EXISTS public.staff_loan_opening_balances (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    staff_id integer NOT NULL,
    employee_no varchar(100),
    loan_type varchar(100) NOT NULL,

    original_amount numeric(14,2) NOT NULL DEFAULT 0,
    term_months integer NOT NULL DEFAULT 0,
    months_paid integer NOT NULL DEFAULT 0,
    per_month numeric(14,2) NOT NULL DEFAULT 0,
    remaining_balance numeric(14,2) NOT NULL DEFAULT 0,

    start_date date,
    effective_date date,
    status varchar(30) NOT NULL DEFAULT 'Active',
    remarks text,

    created_by integer,
    updated_by integer,
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    updated_at timestamp without time zone NOT NULL DEFAULT now(),

    CONSTRAINT fk_staff_loan_opening_balances_staff
      FOREIGN KEY (staff_id) REFERENCES public.staff(id) ON DELETE CASCADE,

    CONSTRAINT chk_staff_loan_opening_balances_type
      CHECK (
        loan_type IN (
          'Salary Advance',
          'Special Advance',
          'Cash Advance',
          'Motorcycle Loan',
          'Other Loan'
        )
      ),

    CONSTRAINT chk_staff_loan_opening_balances_status
      CHECK (status IN ('Active', 'Paid', 'Cancelled')),

    CONSTRAINT chk_staff_loan_opening_balances_numbers
      CHECK (
        original_amount >= 0
        AND term_months >= 0
        AND months_paid >= 0
        AND months_paid <= term_months
        AND per_month >= 0
        AND remaining_balance >= 0
      )
);

CREATE INDEX IF NOT EXISTS idx_staff_loan_opening_balances_staff_id
  ON public.staff_loan_opening_balances(staff_id);

CREATE INDEX IF NOT EXISTS idx_staff_loan_opening_balances_employee_no
  ON public.staff_loan_opening_balances(employee_no);

CREATE INDEX IF NOT EXISTS idx_staff_loan_opening_balances_status
  ON public.staff_loan_opening_balances(status);

CREATE INDEX IF NOT EXISTS idx_staff_loan_opening_balances_loan_type
  ON public.staff_loan_opening_balances(loan_type);

COMMIT;