BEGIN;

-- =========================================
-- staff_bonus_history
-- =========================================
CREATE TABLE IF NOT EXISTS public.staff_bonus_history (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  staff_id integer NOT NULL,
  employee_no varchar(100),
  bonus_type varchar(30) NOT NULL,
  bonus_month date,
  amount numeric(14,2) NOT NULL DEFAULT 0,
  release_date date,
  remarks text,
  created_by integer,
  created_at timestamp without time zone NOT NULL DEFAULT now(),

  CONSTRAINT fk_staff_bonus_history_staff
    FOREIGN KEY (staff_id)
    REFERENCES public.staff(id)
    ON DELETE CASCADE,

  CONSTRAINT chk_staff_bonus_history_bonus_type
    CHECK (bonus_type IN ('13th Month', '14th Month', '15th Month')),

  CONSTRAINT chk_staff_bonus_history_amount
    CHECK (amount >= 0)
);

-- =========================================
-- Indexes
-- =========================================
CREATE INDEX IF NOT EXISTS idx_staff_bonus_history_staff_id
  ON public.staff_bonus_history(staff_id);

CREATE INDEX IF NOT EXISTS idx_staff_bonus_history_employee_no
  ON public.staff_bonus_history(employee_no);

CREATE INDEX IF NOT EXISTS idx_staff_bonus_history_bonus_month
  ON public.staff_bonus_history(bonus_month);

COMMIT;