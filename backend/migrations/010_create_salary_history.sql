BEGIN;

CREATE TABLE public.salary_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    employee_no VARCHAR(100) NOT NULL,
    effective_date DATE NOT NULL,

    salary NUMERIC(12,2) NOT NULL DEFAULT 0,
    ecola NUMERIC(12,2) NOT NULL DEFAULT 0,

    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_salary_history_employee
        FOREIGN KEY (employee_no)
        REFERENCES public.staff(employee_no)
        ON DELETE CASCADE
);

-- Prevent duplicate entries per employee per date
ALTER TABLE public.salary_history
ADD CONSTRAINT unique_employee_effective_date
UNIQUE (employee_no, effective_date);

-- Index for performance
CREATE INDEX idx_salary_history_employee_no
ON public.salary_history(employee_no);

CREATE INDEX idx_salary_history_effective_date
ON public.salary_history(effective_date);

COMMIT;