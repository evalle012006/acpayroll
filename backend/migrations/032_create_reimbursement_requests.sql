BEGIN;

CREATE TABLE IF NOT EXISTS public.reimbursement_requests (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id integer,
  employee_no varchar(100),
  staff_name varchar(255) NOT NULL,
  description text NOT NULL,
  amount numeric(12,2) NOT NULL DEFAULT 0,
  request_date date,
  status varchar(30) NOT NULL DEFAULT 'Pending',
  attachment_path text,
  rejection_reason text,
  created_by integer,
  approved_by integer,
  approved_at timestamp without time zone,
  rejected_by integer,
  rejected_at timestamp without time zone,
  created_at timestamp without time zone NOT NULL DEFAULT now(),
  updated_at timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_reimbursement_requests_employee_id
  ON public.reimbursement_requests(employee_id);

CREATE INDEX IF NOT EXISTS idx_reimbursement_requests_employee_no
  ON public.reimbursement_requests(employee_no);

CREATE INDEX IF NOT EXISTS idx_reimbursement_requests_status
  ON public.reimbursement_requests(status);

CREATE INDEX IF NOT EXISTS idx_reimbursement_requests_request_date
  ON public.reimbursement_requests(request_date);

COMMIT;