BEGIN;

-- =========================
-- logistic_packages
-- =========================
CREATE TABLE IF NOT EXISTS public.logistic_packages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_no varchar(100) NOT NULL UNIQUE,
    sender_name varchar(150),
    receiver_name varchar(150),
    origin_branch varchar(150),
    destination_branch varchar(150),
    current_location varchar(150),
    current_status varchar(100) DEFAULT 'Pending',
    assigned_to varchar(150),
    remarks text,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp DEFAULT CURRENT_TIMESTAMP
);

-- =========================
-- logistic_tracking_history
-- =========================
CREATE TABLE IF NOT EXISTS public.logistic_tracking_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id integer NOT NULL REFERENCES public.logistic_packages(id) ON DELETE CASCADE,
    location varchar(150),
    status varchar(100),
    remarks text,
    updated_by varchar(150),
    created_at timestamp DEFAULT CURRENT_TIMESTAMP
);


ALTER TABLE public.logistic_packages
    ADD COLUMN IF NOT EXISTS courier_name VARCHAR(100),
    ADD COLUMN IF NOT EXISTS external_tracking_no VARCHAR(150),
    ADD COLUMN IF NOT EXISTS last_synced_at TIMESTAMP,
    ADD COLUMN IF NOT EXISTS sync_source VARCHAR(100);


ALTER TABLE public.logistic_tracking_history
    ADD COLUMN IF NOT EXISTS external_event_id VARCHAR(150),
    ADD COLUMN IF NOT EXISTS raw_payload JSONB;

COMMIT;