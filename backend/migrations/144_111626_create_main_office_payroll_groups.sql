BEGIN;

CREATE TABLE IF NOT EXISTS public.main_office_payroll_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_key TEXT NOT NULL UNIQUE,
  group_name TEXT NOT NULL UNIQUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.main_office_payroll_groups
  (group_key, group_name, sort_order)
VALUES
  ('admin_main_office', 'ADMIN-MAIN OFFICE', 1),
  ('tread_lms', 'TREAD & LMS', 2),
  ('audit', 'AUDIT', 3),
  ('svp_vp_avp_operation', 'SVP, VP & AVP-OPERATION', 4),
  ('rm_arm_operation', 'RM & ARM-OPERATION', 5),
  ('am_operation', 'AM-OPERATION', 6),
  ('aam_operation', 'AAM OPERATION', 7),
  ('nao_staff', 'NO ADMIN ORDER STAFF', 8)
ON CONFLICT (group_key) DO NOTHING;

ALTER TABLE public.staff
ADD COLUMN IF NOT EXISTS payroll_group_id BIGINT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'staff_payroll_group_id_fkey'
      AND conrelid = 'public.staff'::regclass
  ) THEN
    ALTER TABLE public.staff
    ADD CONSTRAINT staff_payroll_group_id_fkey
    FOREIGN KEY (payroll_group_id)
    REFERENCES public.main_office_payroll_groups(id)
    ON DELETE SET NULL;
  END IF;
END $$;

UPDATE public.staff AS s
SET payroll_group_id = g.id
FROM public.main_office_payroll_groups AS g
WHERE s.payroll_group_id IS NULL
  AND (
    LOWER(TRIM(s.payroll_group)) = g.group_key
    OR (
      g.group_key = 'aam_operation'
      AND LOWER(TRIM(s.payroll_group)) IN (
        'aam_1_operation',
        'aam_2_operation'
      )
    )
  );

COMMIT;