BEGIN;

CREATE TABLE IF NOT EXISTS public.leave_attachments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_request_id INTEGER NOT NULL,
    file_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_mime TEXT,
    file_size BIGINT,
    uploaded_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_leave_attachments_leave_request
      FOREIGN KEY (leave_request_id)
      REFERENCES public.leave_requests(id)
      ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_leave_attachments_leave_request_id
ON public.leave_attachments(leave_request_id);

CREATE INDEX IF NOT EXISTS idx_leave_attachments_uploaded_at
ON public.leave_attachments(uploaded_at);

COMMIT;

BEGIN;

ALTER TABLE public.leave_requests
DROP COLUMN IF EXISTS attachment_name,
DROP COLUMN IF EXISTS attachment_path,
DROP COLUMN IF EXISTS attachment_mime;

COMMIT;