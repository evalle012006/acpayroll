BEGIN;

CREATE TABLE IF NOT EXISTS public.status_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no VARCHAR(100) NOT NULL,
    effective_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    reason VARCHAR(100),
    remarks TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_status_history_employee_no
      FOREIGN KEY (employee_no)
      REFERENCES public.staff(employee_no)
      ON DELETE CASCADE,

    CONSTRAINT chk_status_history_status
      CHECK (status IN ('Active', 'Inactive'))
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_status_history_employee_date_status
ON public.status_history (employee_no, effective_date, status);

CREATE INDEX IF NOT EXISTS idx_status_history_employee_no
ON public.status_history (employee_no);

CREATE INDEX IF NOT EXISTS idx_status_history_effective_date
ON public.status_history (effective_date);

COMMIT;